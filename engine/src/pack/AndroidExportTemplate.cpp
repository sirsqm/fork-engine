std::string android_settings_gradle() {
    // Names the one module. A single-module project needs no `includeBuild` or
    // plugin management block; the Android Gradle Plugin is resolved from the
    // root build file's `plugins` block against the Google Maven repository.
    std::string text;
    text += "// Generated by fork_export --target android. Do not edit.\n";
    text += "pluginManagement {\n";
    text += "  repositories {\n";
    text += "    google()\n";
    text += "    mavenCentral()\n";
    text += "  }\n";
    text += "}\n";
    text += "dependencyResolutionManagement {\n";
    text += "  repositories {\n";
    text += "    google()\n";
    text += "    mavenCentral()\n";
    text += "  }\n";
    text += "}\n";
    text += "\n";
    text += "rootProject.name = \"fork-engine-game\"\n";
    text += "include(\":app\")\n";
    return text;
}

std::string android_root_build_gradle() {
    // The plugin is declared here and applied in the app module, so its version
    // lives in exactly one place. A version newer than 8.0 is required for the
    // `namespace` and `ndkVersion` fields the app module uses.
    std::string text;
    text += "// Generated by fork_export --target android. Do not edit.\n";
    text += "plugins {\n";
    text += "  id 'com.android.application' version '8.5.0' apply false\n";
    text += "}\n";
    return text;
}

std::string android_gradle_properties() {
    // The AndroidX flag is required by every modern Android Gradle Plugin; the
    // heap is raised because a native build plus the plugin's own work does not
    // fit Gradle's 512 MiB default.
    std::string text;
    text += "# Generated by fork_export --target android. Do not edit.\n";
    text += "android.useAndroidX=true\n";
    text += "org.gradle.jvmargs=-Xmx2048m\n";
    return text;
}

std::string android_app_build_gradle(const ExportManifest& manifest, const AndroidProjectOptions& options) {
    const std::string application_id = resolve_application_id(manifest, options);

    // The app module: an Android application whose native code is the player,
    // built from source by the engine's own CMakeLists through the NDK. The
    // assets directory is the pack and the manifest the export wrote beside this
    // project, so the Gradle plugin packages exactly what was exported.
    std::string text;
    text += "// Generated by fork_export --target android. Do not edit.\n";
    text += "plugins {\n";
    text += "  id 'com.android.application'\n";
    text += "}\n";
    text += "\n";
    text += "android {\n";
    text += "  namespace " + quote(application_id) + "\n";
    text += "  compileSdk " + std::to_string(options.target_sdk) + "\n";
    text += "\n";
    text += "  defaultConfig {\n";
    text += "    applicationId " + quote(application_id) + "\n";
    text += "    minSdk " + std::to_string(options.min_sdk) + "\n";
    text += "    targetSdk " + std::to_string(options.target_sdk) + "\n";
    text += "    versionCode 1\n";
    text += "    versionName " + quote(manifest.engine_version.empty() ? "1.0" : manifest.engine_version) + "\n";
    // The native build the manifest's activity loads. The library name must
    // match what the JNI CMakeLists produces, or the activity starts and finds
    // no library.
    text += "    ndk {\n";
    text += "      abiFilters 'arm64-v8a', 'x86_64'\n";
    text += "    }\n";
    text += "  }\n";
    text += "\n";
    text += "  externalNativeBuild {\n";
    text += "    cmake {\n";
    text += "      path " + quote("src/main/jni/CMakeLists.txt") + "\n";
    text += "    }\n";
    text += "  }\n";
    text += "\n";
    text += "  buildTypes {\n";
    text += "    release {\n";
    text += "      minifyEnabled false\n";
    text += "    }\n";
    text += "  }\n";
    text += "}\n";
    return text;
}

std::string android_manifest_xml(const ExportManifest& manifest, const AndroidProjectOptions& options) {
    const std::string application_id = resolve_application_id(manifest, options);
    const std::string label = manifest.name.empty() ? std::string("Fork Engine Game") : manifest.name;

    // A native activity: the app's entry point is the player's `android_main`,
    // so there is no Java activity and no JNI glue beyond the library the system
    // loads. `hasCode="false"` is what tells Android not to expect a dex with an
    // activity in it, and the library the activity loads is the one the JNI
    // CMakeLists builds.
    //
    // The window is fullscreen and landscape-agnostic: a game chooses its own
    // orientation through the engine, and `configChanges` keeps the activity
    // alive across a rotation or a keyboard, which the native activity handles
    // itself.
    std::string xml;
    xml += "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n";
    xml += "<!-- Generated by fork_export --target android. Do not edit. -->\n";
    xml += "<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\">\n";
    xml += "\n";
    xml += "  <application\n";
    xml += "      android:label=" + quote(label) + "\n";
    xml += "      android:hasCode=\"false\"\n";
    xml += "      android:allowBackup=\"false\">\n";
    xml += "    <activity\n";
    xml += "        android:name=\"android.app.NativeActivity\"\n";
    xml += "        android:exported=\"true\"\n";
    xml += "        android:configChanges=\"orientation|keyboardHidden|screenSize|screenLayout\"\n";
    xml += "        android:theme=\"@android:style/Theme.NoTitleBar.Fullscreen\">\n";
    xml += "      <meta-data android:name=\"android.app.lib_name\" android:value=" + quote(options.native_library) +
           " />\n";
    xml += "      <intent-filter>\n";
    xml += "        <action android:name=\"android.intent.action.MAIN\" />\n";
    xml += "        <category android:name=\"android.intent.category.LAUNCHER\" />\n";
    xml += "      </intent-filter>\n";
    xml += "    </activity>\n";
    xml += "  </application>\n";
    xml += "</manifest>\n";
    // The application id is the namespace; the manifest itself carries no
    // package attribute, which the Android Gradle Plugin derives from it.
    (void)application_id;
    return xml;
}

std::string android_jni_cmake_lists(const AndroidProjectOptions& options) {
    // The native half: the player, built from the engine's source for the
    // phone's ABI. The engine's own CMakeLists is added as a subdirectory so the
    // same FE_PLATFORM_ANDROID path the toolchain file selects is what builds
    // here - the export does not reimplement the engine's build, it points at
    // it. Both source paths are expected absolute so Gradle's working directory
    // cannot change what is built.
    //
    // The library is SHARED because it is what the manifest's native activity
    // loads by name; a static library would be linked into nothing.
    std::string text;
    text += "# Generated by fork_export --target android. Do not edit.\n";
    text += "cmake_minimum_required(VERSION 3.22)\n";
    text += "\n";
    text += "# A game ships a runtime, not an editor or a test suite. These are the\n";
    text += "# same defaults the Android toolchain file sets, restated here so a build\n";
    text += "# driven by Gradle alone cannot pick up the whole desktop tree.\n";
    text += "set(FE_BUILD_EDITOR OFF CACHE BOOL \"\" FORCE)\n";
    text += "set(FE_BUILD_TESTS OFF CACHE BOOL \"\" FORCE)\n";
    text += "set(FE_BUILD_BENCHMARKS OFF CACHE BOOL \"\" FORCE)\n";
    text += "set(FE_BUILD_EXAMPLES OFF CACHE BOOL \"\" FORCE)\n";
    text += "\n";
    text += "# The engine is the project: adding it as a subdirectory builds its\n";
    text += "# libraries for the ABI the NDK toolchain selected, with the Android\n";
    text += "# platform path (FE_PLATFORM_ANDROID) the toolchain file chooses.\n";
    text += "add_subdirectory(" + quote(options.engine_source_dir) + " engine)\n";
    text += "\n";
    text += "# The shipped runtime, built for Android rather than copied. It links the\n";
    text += "# engine and nothing else, exactly as the desktop fork_player does.\n";
    text += "add_library(" + options.native_library + " SHARED " + quote(options.player_source) + ")\n";
    text += "target_link_libraries(" + options.native_library + " PRIVATE FE::engine)\n";
    text += "target_compile_features(" + options.native_library + " PRIVATE cxx_std_20)\n";
    text += "\n";
    text += "# The Android system libraries the runtime's window backend needs.\n";
    text += "find_library(FE_ANDROID_LIB android)\n";
    text += "find_library(FE_LOG_LIB log)\n";
    text += "if(FE_ANDROID_LIB)\n";
    text += "  target_link_libraries(" + options.native_library + " PRIVATE ${FE_ANDROID_LIB})\n";
    text += "endif()\n";
    text += "if(FE_LOG_LIB)\n";
    text += "  target_link_libraries(" + options.native_library + " PRIVATE ${FE_LOG_LIB})\n";
    text += "endif()\n";
    return text;
}

Error write_android_project(const std::string& out_dir, const ExportManifest& manifest,
                            const AndroidProjectOptions& options) {
    if (manifest.pack.empty() || manifest.scene.empty()) {
        return Error("android export template: the manifest names no pack or scene");
    }

    struct File {
        const char* relative_path;
        std::string text;
    };
    const File files[] = {
        {AndroidExportNames::kSettingsGradle, android_settings_gradle()},
        {AndroidExportNames::kRootBuildGradle, android_root_build_gradle()},
        {AndroidExportNames::kGradleProperties, android_gradle_properties()},
        {AndroidExportNames::kAppBuildGradle, android_app_build_gradle(manifest, options)},
        {AndroidExportNames::kAndroidManifest, android_manifest_xml(manifest, options)},
        {AndroidExportNames::kJniCMakeLists, android_jni_cmake_lists(options)},
    };

    // Create every directory first, then write: a failure leaves no file
    // pointing at a directory that does not exist.
    for (const File& file : files) {
        const std::string path = fs::join(out_dir, file.relative_path);
        if (Error error = fs::create_directories(fs::parent_path(path)); error) {
            return error;
        }
    }
    for (const File& file : files) {
        const std::string path = fs::join(out_dir, file.relative_path);
        if (Error error = fs::write_text_file(path, file.text); error) {
            return error;
        }
    }
    // The assets directory must exist even before the pack is copied into it, so
    // a Gradle run that finds it empty is a valid project rather than a missing
    // source set.
    if (Error error = fs::create_directories(fs::join(out_dir, AndroidExportNames::kAssetsDir)); error) {
        return error;
    }

    return Error::none();
}

