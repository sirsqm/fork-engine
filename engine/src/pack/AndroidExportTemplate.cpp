// A value for embedding in a Gradle or CMake string. Gradle's Groovy strings and
// CMake's quoted strings share the backslash and double-quote escapes, so one
// escaper serves both. Without it a project name with a quote would break out of
// the literal and produce a build file that does not parse - the same reason the
// web shell escapes through a JSON serialiser.
[[nodiscard]] std::string quote(const std::string& value) {
    std::string out;
    out.reserve(value.size() + 2);
    out.push_back('"');
    for (const char c : value) {
        if (c == '\\' || c == '"') {
            out.push_back('\\');
        }
        out.push_back(c);
    }
    out.push_back('"');
    return out;
}

// The application id, made a valid Java package from the project name. Android
// requires a dotted identifier of letters, digits and underscores, each segment
// starting with a letter; a project named "My Game" would otherwise produce an
// id Gradle rejects. Segments are lowercased because the Play Store requires an
// all-lowercase application id, and a name that ships to a store must not need
// fixing afterwards. The default is used only when the project names none, so
// this is a convenience rather than a constraint on the caller.
[[nodiscard]] std::string sanitise_package(const std::string& name) {
    std::string out;
    bool last_was_dot = true; // so a leading separator is not emitted
    for (const char c : name) {
        const bool alnum = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
        if (alnum) {
            const char lower = (c >= 'A' && c <= 'Z') ? static_cast<char>(c - 'A' + 'a') : c;
            out.push_back(lower);
            last_was_dot = false;
        } else if (!last_was_dot) {
            out.push_back('.');
            last_was_dot = true;
        }
    }
    // A trailing separator is not a valid id segment.
    while (!out.empty() && out.back() == '.') {
        out.pop_back();
    }
    // An id segment may not start with a digit.
    if (!out.empty() && out.front() >= '0' && out.front() <= '9') {
        out.insert(out.begin(), 'x');
    }
    return out.empty() ? std::string("game") : out;
}

[[nodiscard]] std::string resolve_application_id(const ExportManifest& manifest, const AndroidProjectOptions& options) {
    if (!options.application_id.empty()) {
        return options.application_id;
    }
    const std::string stem = manifest.name.empty() ? std::string("game") : manifest.name;
    return "com.forkengine." + sanitise_package(stem);
}

