// A value for embedding in a CMake quoted string. Escapes the backslash and the
// double quote, the two characters that would otherwise break out of the
// literal. Without it a project name with a quote would produce a project file
// that does not parse - the same reason the Android template quotes its values.
[[nodiscard]] std::string quote(const std::string& value) {
    std::string out;
    out.reserve(value.size() + 2);
    out.push_back('"');
    for (const char c : value) {
        if (c == '\\' || c == '"') {
            out.push_back('\\');
        }
        out.push_back(c);
    }
    out.push_back('"');
    return out;
}

// A value for embedding in XML text. A plist is XML, and a game named "Tom &
// Jerry" would otherwise produce a file that does not parse and an app that does
// not launch. Escapes the five predefined entities; the `&` must be first or it
// would double-escape the others.
[[nodiscard]] std::string xml_escape(const std::string& value) {
    std::string out;
    out.reserve(value.size());
    for (const char c : value) {
        switch (c) {
        case '&':
            out += "&amp;";
            break;
        case '<':
            out += "&lt;";
            break;
        case '>':
            out += "&gt;";
            break;
        case '"':
            out += "&quot;";
            break;
        case '\'':
            out += "&apos;";
            break;
        default:
            out.push_back(c);
            break;
        }
    }
    return out;
}

// The bundle identifier, made a valid reverse-DNS id from the project name.
// Apple requires a dotted identifier of letters, digits and hyphens; a project
// named "My Game" would otherwise produce an id the signing tools reject. It is
// lowercased because the conventional form is lowercase and an id that ships to
// the App Store should not need fixing afterwards. The default is used only when
// the project names none, so this is a convenience rather than a constraint.
[[nodiscard]] std::string sanitise_bundle_id(const std::string& name) {
    std::string out;
    bool last_was_dot = true; // so a leading separator is not emitted
    for (const char c : name) {
        const bool alnum = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
        if (alnum) {
            const char lower = (c >= 'A' && c <= 'Z') ? static_cast<char>(c - 'A' + 'a') : c;
            out.push_back(lower);
            last_was_dot = false;
        } else if (!last_was_dot) {
            out.push_back('.');
            last_was_dot = true;
        }
    }
    while (!out.empty() && out.back() == '.') {
        out.pop_back();
    }
    if (!out.empty() && out.front() >= '0' && out.front() <= '9') {
        out.insert(out.begin(), 'x');
    }
    return out.empty() ? std::string("game") : out;
}

[[nodiscard]] std::string resolve_bundle_id(const ExportManifest& manifest, const IosProjectOptions& options) {
    if (!options.bundle_id.empty()) {
        return options.bundle_id;
    }
    const std::string stem = manifest.name.empty() ? std::string("game") : manifest.name;
    return "com.forkengine." + sanitise_bundle_id(stem);
}

// The human-readable app name, for the plist's display name.
[[nodiscard]] std::string display_name(const ExportManifest& manifest) {
    return manifest.name.empty() ? std::string("Fork Engine Game") : manifest.name;
}

