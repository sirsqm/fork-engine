std::string ios_project_cmake_lists(const ExportManifest& manifest, const IosProjectOptions& options) {
    const std::string bundle_id = resolve_bundle_id(manifest, options);
    const std::string version = manifest.engine_version.empty() ? std::string("1.0") : manifest.engine_version;

    // A CMake project that builds the player as a macOS/iOS app bundle. The
    // caller configures it with the iOS toolchain (cmake/toolchains/ios.cmake),
    // which is what turns `MACOSX_BUNDLE` into an iOS .app and selects the SDK.
    // The engine is added as a subdirectory so its libraries are built for the
    // target from the checkout the export was pointed at, exactly as the Android
    // project does.
    std::string text;
    text += "# Generated by fork_export --target ios. Do not edit.\n";
    text += "cmake_minimum_required(VERSION 3.22)\n";
    text += "\n";
    text += "# A game ships a runtime, not an editor or a test suite. These are the\n";
    text += "# same defaults the iOS toolchain file sets, restated here so a build\n";
    text += "# driven by Xcode alone cannot pick up the whole desktop tree.\n";
    text += "set(FE_BUILD_EDITOR OFF CACHE BOOL \"\" FORCE)\n";
    text += "set(FE_BUILD_TESTS OFF CACHE BOOL \"\" FORCE)\n";
    text += "set(FE_BUILD_BENCHMARKS OFF CACHE BOOL \"\" FORCE)\n";
    text += "set(FE_BUILD_EXAMPLES OFF CACHE BOOL \"\" FORCE)\n";
    text += "\n";
    text += "project(ForkEngineGame LANGUAGES CXX)\n";
    text += "\n";
    text += "# The engine is the project: adding it as a subdirectory builds its\n";
    text += "# libraries for the SDK the iOS toolchain selected, with the iOS\n";
    text += "# platform path (FE_PLATFORM_IOS) the toolchain file chooses.\n";
    text += "add_subdirectory(" + quote(options.engine_source_dir) + " engine)\n";
    text += "\n";
    text += "# The shipped runtime, built as an app bundle. MACOSX_BUNDLE is what\n";
    text += "# makes CMake produce a .app rather than a bare executable; under the iOS\n";
    text += "# toolchain it is an iOS .app.\n";
    text += "add_executable(fork_player MACOSX_BUNDLE " + quote(options.player_source) + ")\n";
    text += "target_link_libraries(fork_player PRIVATE FE::engine)\n";
    text += "target_compile_features(fork_player PRIVATE cxx_std_20)\n";
    text += "\n";
    text += "set_target_properties(fork_player PROPERTIES\n";
    text += "  MACOSX_BUNDLE_BUNDLE_NAME " + quote(display_name(manifest)) + "\n";
    text += "  MACOSX_BUNDLE_GUI_IDENTIFIER " + quote(bundle_id) + "\n";
    text +=
        "  MACOSX_BUNDLE_INFO_PLIST \"${CMAKE_CURRENT_SOURCE_DIR}/" + std::string(IosExportNames::kInfoPlist) + "\"\n";
    text += "  MACOSX_BUNDLE_BUNDLE_VERSION " + quote(version) + "\n";
    text += "  MACOSX_BUNDLE_SHORT_VERSION_STRING " + quote(version) + "\n";
    text += ")\n";
    text += "\n";
    text += "# The pack and the manifest travel in the bundle's Resources, which is\n";
    text += "# where the runtime reads them from the app the way it reads them from\n";
    text += "# disk on desktop.\n";
    text += "add_custom_command(\n";
    text += "  TARGET fork_player POST_BUILD\n";
    text += "  COMMAND ${CMAKE_COMMAND} -E copy_directory\n";
    text += "          \"${CMAKE_CURRENT_SOURCE_DIR}/" + std::string(IosExportNames::kAssetsDir) + "\"\n";
    text += "          \"$<TARGET_BUNDLE_CONTENT_DIR:fork_player>/Resources\"\n";
    text += "  COMMENT \"Copying the pack and manifest into the app bundle\"\n";
    text += ")\n";
    return text;
}

std::string ios_info_plist(const ExportManifest& manifest, const IosProjectOptions& options) {
    const std::string bundle_id = resolve_bundle_id(manifest, options);
    const std::string version = manifest.engine_version.empty() ? std::string("1.0") : manifest.engine_version;

    // A complete app Info.plist: the keys iOS requires for an app to launch, not
    // a fragment. CFBundleExecutable must name the bundle's executable, which
    // CMake names after the target; CFBundleIdentifier is the signing identity;
    // the launch and orientation keys are what make it a fullscreen game rather
    // than a windowed app that iOS rejects. The values are substituted here
    // rather than left as @VARS@ for CMake, because the file is generated, not a
    // template - one less indirection to get wrong.
    std::string text;
    text += "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
    text += "<!-- Generated by fork_export --target ios. Do not edit. -->\n";
    text += "<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" "
            "\"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n";
    text += "<plist version=\"1.0\">\n";
    text += "<dict>\n";
    text += "  <key>CFBundleDevelopmentRegion</key>\n";
    text += "  <string>en</string>\n";
    text += "  <key>CFBundleExecutable</key>\n";
    text += "  <string>fork_player</string>\n";
    text += "  <key>CFBundleIdentifier</key>\n";
    text += "  <string>" + xml_escape(bundle_id) + "</string>\n";
    text += "  <key>CFBundleInfoDictionaryVersion</key>\n";
    text += "  <string>6.0</string>\n";
    text += "  <key>CFBundleName</key>\n";
    text += "  <string>" + xml_escape(display_name(manifest)) + "</string>\n";
    text += "  <key>CFBundleDisplayName</key>\n";
    text += "  <string>" + xml_escape(display_name(manifest)) + "</string>\n";
    text += "  <key>CFBundlePackageType</key>\n";
    text += "  <string>APPL</string>\n";
    text += "  <key>CFBundleShortVersionString</key>\n";
    text += "  <string>" + xml_escape(version) + "</string>\n";
    text += "  <key>CFBundleVersion</key>\n";
    text += "  <string>" + xml_escape(version) + "</string>\n";
    text += "  <key>MinimumOSVersion</key>\n";
    text += "  <string>" + xml_escape(options.deployment_target) + "</string>\n";
    text += "  <key>CFBundleSupportedPlatforms</key>\n";
    text += "  <array>\n";
    text += "    <string>iPhoneOS</string>\n";
    text += "  </array>\n";
    text += "  <key>UIDeviceFamily</key>\n";
    text += "  <array>\n";
    text += "    <integer>1</integer>\n";
    text += "    <integer>2</integer>\n";
    text += "  </array>\n";
    text += "  <key>UILaunchScreen</key>\n";
    text += "  <dict/>\n";
    text += "  <key>UIRequiredDeviceCapabilities</key>\n";
    text += "  <array>\n";
    text += "    <string>arm64</string>\n";
    text += "  </array>\n";
    text += "  <key>UIStatusBarHidden</key>\n";
    text += "  <true/>\n";
    text += "  <key>UIViewControllerBasedStatusBarAppearance</key>\n";
    text += "  <false/>\n";
    text += "  <key>UISupportedInterfaceOrientations</key>\n";
    text += "  <array>\n";
    text += "    <string>UIInterfaceOrientationLandscapeLeft</string>\n";
    text += "    <string>UIInterfaceOrientationLandscapeRight</string>\n";
    text += "  </array>\n";
    text += "</dict>\n";
    text += "</plist>\n";
    return text;
}

Error write_ios_project(const std::string& out_dir, const ExportManifest& manifest, const IosProjectOptions& options) {
    if (manifest.pack.empty() || manifest.scene.empty()) {
        return Error("ios export template: the manifest names no pack or scene");
    }

    struct File {
        const char* relative_path;
        std::string text;
    };
    const File files[] = {
        {IosExportNames::kProjectCMakeLists, ios_project_cmake_lists(manifest, options)},
        {IosExportNames::kInfoPlist, ios_info_plist(manifest, options)},
    };

    // Create every directory first, then write: a failure leaves no file
    // pointing at a directory that does not exist.
    for (const File& file : files) {
        const std::string path = fs::join(out_dir, file.relative_path);
        if (Error error = fs::create_directories(fs::parent_path(path)); error) {
            return error;
        }
    }
    for (const File& file : files) {
        const std::string path = fs::join(out_dir, file.relative_path);
        if (Error error = fs::write_text_file(path, file.text); error) {
            return error;
        }
    }
    // The assets directory must exist even before the pack is copied into it, so
    // a build that finds it empty is a valid project rather than a missing copy
    // source.
    if (Error error = fs::create_directories(fs::join(out_dir, IosExportNames::kAssetsDir)); error) {
        return error;
    }

    return Error::none();
}

