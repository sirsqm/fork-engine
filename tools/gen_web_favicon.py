#!/usr/bin/env python3
"""Generates the favicon a web export carries.

A game exported to the web is opened as a browser page, and the tab shows the
favicon: without one the browser shows a blank page icon, which reads as an
unfinished export. The mark is the project's own, from
`branding/forkengine-logo-white.svg`.

The favicon is an SVG with a `prefers-color-scheme` rule, so it is black on a
light tab bar and white on a dark one - the same black/white pair the window
icon uses, for the same reason: a white mark on a white tab is invisible.

The SVG is emitted as a C++ raw string literal rather than a file the export
copies, because the export must not depend on the source tree at run time: a
game is exported on a machine that may have only the installed tree. The header
is generated and committed, the same way `EngineIconMask.h` is, so the build
never needs Python (see cmake/FEDependencies.cmake).

Output (relative to the repository root):

    engine/src/pack/WebFavicon.h

Run:  python3 tools/gen_web_favicon.py
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "branding" / "forkengine-logo-white.svg"
OUT = ROOT / "engine" / "src" / "pack" / "WebFavicon.h"


def main() -> None:
    source = SVG.read_text()

    # Keep the geometry (the viewBox and the path data) and replace the fixed
    # white fill with a rule that follows the browser's colour scheme.
    view_box = re.search(r'viewBox="([^"]+)"', source)
    if view_box is None:
        raise SystemExit("the logo SVG has no viewBox")
    paths = re.findall(r"<path\b[^>]*\bd=\"([^\"]+)\"", source)
    if not paths:
        raise SystemExit("the logo SVG has no paths")

    body = "\n".join(f'  <path d="{d}"/>' for d in paths)
    favicon = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box.group(1)}">'
        "<style>path{fill:#000}@media(prefers-color-scheme:dark){path{fill:#fff}}</style>\n"
        f"{body}\n"
        "</svg>\n"
    )

    OUT.write_text(
        "// Copyright (c) 2026 sqm\n"
        "// SPDX-License-Identifier: MIT\n"
        "//\n"
        "// Generated by tools/gen_web_favicon.py - do not edit by hand.\n"
        "//\n"
        "// The fork emblem as an SVG favicon, black on a light tab bar and white on\n"
        "// a dark one. Regenerate from branding/forkengine-logo-white.svg after any\n"
        "// change to the mark.\n"
        "#pragma once\n"
        "\n"
        "namespace fe::pack {\n"
        "\n"
        "inline constexpr const char* kWebFaviconSvg = R\"FE_FAVICON(" + favicon + ")FE_FAVICON\";\n"
        "\n"
        "} // namespace fe::pack\n"
    )
    # The raw-string body is emitted at its own width; run clang-format so a
    # fresh generation matches the checked-in file and the CI format check.
    subprocess.run(["clang-format", "-i", str(OUT)], check=True)
    print(f"wrote {OUT} ({len(favicon)} bytes of SVG)")


if __name__ == "__main__":
    main()
