#!/usr/bin/env python3
"""Generates the icon the Linux AppImage carries.

An AppImage requires an icon: appimagetool refuses to build one whose desktop
entry names an image that is not in the AppDir. The project generates its binary
assets rather than checking in hand-drawn blobs (see tools/gen_breakout_assets.py),
so the icon is generated the same way - with `struct` + `zlib`, no image library
and no network - and regenerated by re-running this script.

The icon is the project's own mark: the fork emblem from
`branding/forkengine-logo-white.svg`, rendered white on the dark tile the engine
and the web shell already use, so the download looks like the engine. The
geometry comes from `tools/brand_raster.py`, which is also what generates the
window icon, so the two cannot drift into different interpretations of the mark.

Output (relative to the repository root):

    packaging/fork-engine.png   (256x256 RGBA)

Run:  python3 tools/gen_appimage_icon.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brand_raster  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "branding" / "forkengine-logo-white.svg"
OUT = ROOT / "packaging" / "fork-engine.png"

SIZE = 256
# The dark field the engine's own shell uses (the web export template's
# theme-color), so the icon and the running game are the same colour.
TILE = (16, 16, 20)
INK = (255, 255, 255)
CORNER_RADIUS = 52
# The emblem does not touch the tile edge; an icon that does reads as clipped.
MARGIN = 0.17


def rounded_tile(size, radius):
    """Coverage of a rounded square, anti-aliased by 4x4 supersampling.

    A desktop icon is a square image, so the round corners have to be in the
    pixels rather than left to the shell. The edge is the only place coverage is
    fractional; the interior is solid.
    """
    coverage = bytearray(size * size)
    samples = 4
    for y in range(size):
        for x in range(size):
            inside = 0
            for sy in range(samples):
                for sx in range(samples):
                    px = x + (sx + 0.5) / samples
                    py = y + (sy + 0.5) / samples
                    # Clamp to the inner rectangle, then require the corner
                    # circle: the rounded-rectangle distance test.
                    cx = min(max(px, radius), size - radius)
                    cy = min(max(py, radius), size - radius)
                    dx = px - cx
                    dy = py - cy
                    if dx * dx + dy * dy <= radius * radius:
                        inside += 1
            coverage[y * size + x] = (inside * 255) // (samples * samples)
    return coverage


def main() -> None:
    tile = rounded_tile(SIZE, CORNER_RADIUS)
    emblem = brand_raster.rasterize(SVG.read_text(), SIZE, SIZE, margin=MARGIN)

    pixels = bytearray(SIZE * SIZE * 4)
    for i in range(SIZE * SIZE):
        o = i * 4
        if emblem[i]:
            pixels[o : o + 4] = bytes((*INK, 255))
        else:
            pixels[o : o + 3] = bytes(TILE)
            pixels[o + 3] = tile[i]

    written = brand_raster.write_png(OUT, SIZE, SIZE, bytes(pixels))
    print(f"wrote {OUT} ({written} bytes)")


if __name__ == "__main__":
    main()
