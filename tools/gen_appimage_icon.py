#!/usr/bin/env python3
"""Generates the icon the Linux AppImage carries.

An AppImage requires an icon: appimagetool refuses to build one whose desktop
entry names an image that is not in the AppDir. The project generates its binary
assets rather than checking in hand-drawn blobs (see tools/gen_breakout_assets.py),
so the icon is generated the same way - with `struct` + `zlib`, no image library
and no network - and regenerated by re-running this script.

Output (relative to the repository root):

    packaging/fork-engine.png   (256x256 RGBA)

Run:  python3 tools/gen_appimage_icon.py
"""
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "packaging" / "fork-engine.png"

SIZE = 256


def chunk(tag: bytes, data: bytes) -> bytes:
    return (
        struct.pack(">I", len(data))
        + tag
        + data
        + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    )


def write_png(path: Path, width: int, height: int, pixels: bytes) -> None:
    """Writes an 8-bit RGBA PNG. `pixels` is width*height*4 bytes, row-major."""
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    raw = bytearray()
    stride = width * 4
    for y in range(height):
        raw.append(0)  # filter type 0 (None) for each scanline
        raw.extend(pixels[y * stride : (y + 1) * stride])
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", ihdr)
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)
    print(f"wrote {path} ({len(png)} bytes)")


def main() -> None:
    # A breakout field: three rows of bricks over a paddle and a ball, on the
    # dark field the slice uses. Everything is drawn as axis-aligned rectangles
    # and one disc, so the result is exact and needs no anti-aliasing beyond the
    # circle's own edge test.
    bg = (18, 18, 28, 255)
    buf = bytearray(bg * (SIZE * SIZE))

    def fill_rect(x0: int, y0: int, x1: int, y1: int, colour) -> None:
        for y in range(max(y0, 0), min(y1, SIZE)):
            row = y * SIZE
            for x in range(max(x0, 0), min(x1, SIZE)):
                i = (row + x) * 4
                buf[i : i + 4] = bytes(colour)

    brick_colours = [
        (232, 92, 92, 255),
        (240, 176, 72, 255),
        (108, 196, 232, 255),
    ]
    brick_w, brick_h, gap = 60, 24, 10
    left = (SIZE - (4 * brick_w + 3 * gap)) // 2
    for row, colour in enumerate(brick_colours):
        top = 40 + row * (brick_h + gap)
        for col in range(4):
            x = left + col * (brick_w + gap)
            fill_rect(x, top, x + brick_w, top + brick_h, colour)

    # Paddle.
    fill_rect(SIZE // 2 - 52, 196, SIZE // 2 + 52, 210, (236, 236, 244, 255))

    # Ball, drawn as a filled disc with a hard edge.
    cx, cy, r = SIZE // 2, 160, 14
    for y in range(cy - r, cy + r + 1):
        for x in range(cx - r, cx + r + 1):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
                i = (y * SIZE + x) * 4
                buf[i : i + 4] = bytes((244, 244, 250, 255))

    write_png(OUT, SIZE, SIZE, bytes(buf))


if __name__ == "__main__":
    main()
