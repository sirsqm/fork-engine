#!/usr/bin/env python3
"""Generates the mask behind the engine's window icon.

The engine shows its own mark in the window it opens: the title bar and the task
bar are the first place a running engine is seen, and a default GLFW icon there
looks unfinished. The mark is the fork emblem from
`branding/forkengine-logo-white.svg`.

The emblem is monochrome, so it is stored as a 1-bit coverage mask rather than
as RGBA: 64x64 is 512 bytes instead of 16 KiB, and the ink colour is chosen when
the mask is expanded (white for a dark background, black for a light one). The
geometry comes from `tools/brand_raster.py`, the same rasteriser that produces
the AppImage icon, so every icon is the same mark.

The mask is a generated file that is committed rather than built, for the same
reason `packaging/fork-engine.png` is: the build must never need Python (see
cmake/FEDependencies.cmake). Re-run this script after changing the logo and
commit the result.

Output (relative to the repository root):

    engine/src/platform/EngineIconMask.h

Run:  python3 tools/gen_engine_icon.py
"""
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brand_raster  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "branding" / "forkengine-logo-white.svg"
OUT = ROOT / "engine" / "src" / "platform" / "EngineIconMask.h"

# 64x64 is large enough that the fork tines stay separate and small enough that
# the mask is half a kilobyte. A window icon is scaled by the desktop anyway.
SIZE = 64


def main() -> None:
    mask = brand_raster.rasterize(SVG.read_text(), SIZE, SIZE)

    # Pack one bit per pixel, most-significant bit first within each byte, row by
    # row. A set bit is covered by the mark.
    packed = bytearray()
    for i in range(0, SIZE * SIZE, 8):
        byte = 0
        for bit in range(8):
            if mask[i + bit]:
                byte |= 0x80 >> bit
        packed.append(byte)

    lines = []
    for start in range(0, len(packed), 12):
        row = ", ".join(f"0x{b:02x}" for b in packed[start : start + 12])
        lines.append(f"    {row},")
    body = "\n".join(lines)

    OUT.write_text(
        "// Copyright (c) 2026 sqm\n"
        "// SPDX-License-Identifier: MIT\n"
        "//\n"
        "// Generated by tools/gen_engine_icon.py - do not edit by hand.\n"
        "//\n"
        "// The fork emblem as a 1-bit coverage mask, row-major, most-significant\n"
        "// bit first. Regenerate from branding/forkengine-logo-white.svg after any\n"
        "// change to the mark.\n"
        "#pragma once\n"
        "\n"
        "#include \"fe/core/Types.h\"\n"
        "\n"
        "namespace fe::platform::icon {\n"
        "\n"
        f"inline constexpr u32 kSize = {SIZE};\n"
        "\n"
        "inline constexpr u8 kMask[] = {\n"
        f"{body}\n"
        "};\n"
        "\n"
        f"static_assert(sizeof(kMask) == (kSize * kSize) / 8, \"the mask must cover every pixel\");\n"
        "\n"
        "} // namespace fe::platform::icon\n"
    )
    # The mask rows are emitted at a fixed width, which is not necessarily the
    # width clang-format would choose; run it so a fresh generation matches the
    # checked-in file byte for byte (and so the CI format check passes).
    subprocess.run(["clang-format", "-i", str(OUT)], check=True)
    print(f"wrote {OUT} ({len(packed)} bytes of mask)")


if __name__ == "__main__":
    main()
